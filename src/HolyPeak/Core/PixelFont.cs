        public const int CellH = 9;
        public const int LineHeight = 11;
        public const int Baseline = 7;

        private readonly Texture2D _tex;
        private readonly Dictionary<char, Rectangle> _src = new Dictionary<char, Rectangle>();
        private readonly Dictionary<char, int> _adv = new Dictionary<char, int>();

        public PixelFont(GraphicsDevice gd)
        {
            var glyphs = Glyphs();
            int cols = 16, cellW = 6;
            int rows = (glyphs.Count + cols - 1) / cols;
            int w = cols * cellW, h = rows * CellH;
            var data = new Color[w * h];
            int i = 0;
            foreach (var kv in glyphs)
            {
                int gx = (i % cols) * cellW, gy = (i / cols) * CellH;
                string[] g = kv.Value;
                int width = 0;
                for (int y = 0; y < g.Length; y++)
                    for (int x = 0; x < g[y].Length; x++)
                        if (g[y][x] == '#')
                        {
                            data[(gy + y) * w + gx + x] = Color.White;
                            width = Math.Max(width, x + 1);
                        }
                if (kv.Key == ' ') width = 3;
                _src[kv.Key] = new Rectangle(gx, gy, Math.Max(1, width), CellH);
                _adv[kv.Key] = width + 1;
                i++;
            }
            _tex = new Texture2D(gd, w, h);
            _tex.SetData(data);
        }

        public int CharWidth(char c) => _adv.TryGetValue(c, out int a) ? a : _adv['?'];

        public int Measure(string s)
        {
            int w = 0, best = 0;
            foreach (char c in s)
            {
                if (c == '\n') { best = Math.Max(best, w); w = 0; continue; }
                w += CharWidth(c);
            }
            best = Math.Max(best, w);
            return Math.Max(0, best - 1);
        }

        public Vector2 MeasureBlock(string s)
        {
            int lines = 1;
            foreach (char c in s) if (c == '\n') lines++;
            return new Vector2(Measure(s), lines * LineHeight - (LineHeight - Baseline));
        }

        public void Draw(SpriteBatch sb, string s, Vector2 pos, Color color, float scale = 1f)
        {
            float x = MathF.Round(pos.X), y = MathF.Round(pos.Y);
            float startX = x;
            foreach (char c0 in s)
            {
                char c = c0;
                if (c == '\n') { x = startX; y += LineHeight * scale; continue; }
                if (!_src.TryGetValue(c, out var src)) { c = '?'; src = _src[c]; }
                if (c != ' ')
                    sb.Draw(_tex, new Vector2(x, y), src, color, 0f, Vector2.Zero, scale, SpriteEffects.None, 0f);
                x += _adv[c] * scale;
            }
        }

        /// <summary>Draws text with a 1px drop shadow (or full outline).</summary>
        public void DrawShadowed(SpriteBatch sb, string s, Vector2 pos, Color color, Color shadow, float scale = 1f, bool outline = false)
        {
            if (outline)
            {
                for (int oy = -1; oy <= 1; oy++)
                    for (int ox = -1; ox <= 1; ox++)
                        if (ox != 0 || oy != 0) Draw(sb, s, pos + new Vector2(ox, oy) * scale, shadow, scale);
            }
            else Draw(sb, s, pos + new Vector2(0, 1) * scale, shadow, scale);
            Draw(sb, s, pos, color, scale);
        }

        /// <summary>Draws each line centered horizontally on <paramref name="center"/>.X.</summary>
        public void DrawCentered(SpriteBatch sb, string s, Vector2 center, Color color, Color? shadow = null, float scale = 1f, bool outline = false)
        {
            var lines = s.Split('\n');
            float y = center.Y;
            foreach (var line in lines)
            {
                float w = Measure(line) * scale;
                var p = new Vector2(MathF.Round(center.X - w / 2f), MathF.Round(y));
                if (shadow.HasValue) DrawShadowed(sb, line, p, color, shadow.Value, scale, outline);
                else Draw(sb, line, p, color, scale);
                y += LineHeight * scale;
            }
        }

        public List<string> Wrap(string text, int maxWidth)
        {
            var result = new List<string>();
            foreach (var para in text.Split('\n'))
            {
                string line = "";
                foreach (var word in para.Split(' '))
                {
                    string test = line.Length == 0 ? word : line + " " + word;
                    if (Measure(test) > maxWidth && line.Length > 0) { result.Add(line); line = word; }
                    else line = test;
                }
                result.Add(line);
            }
            return result;
        }

