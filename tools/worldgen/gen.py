"""Authoring helpers for world.txt: rooms are built from rectangles and run-length rows.

A room covers w x h cells of the world grid; each cell is 40 x 23 tiles of 8 px.
Run-length row specs look like '3# 10. 2- 25#' (count + char, separated by spaces).
"""
import re

CW, CH = 40, 23
ROOMS = []


class Room:
    def __init__(self, rid, at, size=(1, 1), region='village', fill='.', **props):
        self.id = rid
        self.at = at
        self.size = size
        self.region = region
        self.w = size[0] * CW
        self.h = size[1] * CH
        self.g = [[fill] * self.w for _ in range(self.h)]
        self.props = dict(props)
        ROOMS.append(self)

    # --- drawing ---
    def r(self, x0, y0, x1, y1, c='#'):
        for y in range(max(0, y0), min(self.h - 1, y1) + 1):
            for x in range(max(0, x0), min(self.w - 1, x1) + 1):
                self.g[y][x] = c
        return self

    def p(self, x, y, c):
        self.g[y][x] = c
        return self

    def fill(self, c='#'):
        return self.r(0, 0, self.w - 1, self.h - 1, c)

    def carve(self, x0, y0, x1, y1, c='.'):
        return self.r(x0, y0, x1, y1, c)

    def over(self, x0, y0, x1, y1, c, only='.:'):
        """Paint c only over cells currently in `only` (keeps terrain)."""
        for y in range(max(0, y0), min(self.h - 1, y1) + 1):
            for x in range(max(0, x0), min(self.w - 1, x1) + 1):
                if self.g[y][x] in only:
                    self.g[y][x] = c
        return self

    def plat(self, x0, x1, y, c='-'):
        return self.r(x0, y, x1, y, c)

    def hline(self, x0, x1, y, c='-'):
        return self.r(x0, y, x1, y, c)

    def vline(self, x, y0, y1, c='#'):
        return self.r(x, y0, x, y1, c)

    def rows(self, start, *specs):
        for i, spec in enumerate(specs):
            self.g[start + i] = list(seg(spec, self.w, self.id, start + i))
        return self

    def frame(self, c='#', t=1):
        """Solid border all round; open edges are cut afterwards with door()."""
        self.r(0, 0, self.w - 1, t - 1, c)
        self.r(0, self.h - t, self.w - 1, self.h - 1, c)
        self.r(0, 0, t - 1, self.h - 1, c)
        self.r(self.w - t, 0, self.w - 1, self.h - 1, c)
        return self

    def door(self, side, a, b, depth=1):
        """Open the border on a side between tile coordinates a..b (inclusive)."""
        for i in range(a, b + 1):
            for d in range(depth):
                if side == 'L': self.g[i][d] = '.'
                if side == 'R': self.g[i][self.w - 1 - d] = '.'
                if side == 'T': self.g[d][i] = '.'
                if side == 'B': self.g[self.h - 1 - d][i] = '.'
        return self

    def text(self):
        return [''.join(row) for row in self.g]


def seg(spec, w, rid, y):
    out = ''
    for tok in spec.split():
        m = re.fullmatch(r'(\d+)(.)', tok)
        out += m.group(2) * int(m.group(1)) if m else tok
    if len(out) != w:
        raise Exception(f'{rid} row {y}: length {len(out)} != {w}: {spec}')
    return out


def write(path):
    with open(path, 'w') as f:
        f.write('// HOLY PEAK - the mountain. Generated by tools/worldgen; see Atlas.cs for the format\n')
        f.write('// and Room.cs for the map legend.\n\n')
        for rm in ROOMS:
            f.write(f'@room {rm.id} at={rm.at[0]},{rm.at[1]} size={rm.size[0]},{rm.size[1]} region={rm.region}\n')
            for k, v in rm.props.items():
                f.write(f'{k}: {v}\n')
            f.write('@map\n')
            for row in rm.text():
                f.write(row + '\n')
            f.write('@end\n\n')
